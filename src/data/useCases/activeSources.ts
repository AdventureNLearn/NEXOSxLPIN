export function getActiveSourcesForDesk(useCaseId: string): ActiveSource[] {
  const desk =
    BY_DESK[useCaseId] ??
    CONGRESS_SOURCES_BY_DESK[useCaseId] ??
    CORPUS_SOURCES[useCaseId] ??
    []
  // Desk-specific first, then shared tools (dedupe by id)
  const seen = new Set<string>()
  const out: ActiveSource[] = []
  for (const src of [...desk, ...SHARED_VERIFY_TOOLS]) {
    if (seen.has(src.id)) continue
    seen.add(src.id)
    out.push(src)
  }
  return out
}

export function sourcesAsPackRefs(sources: ActiveSource[]) {
  return sources.map((src) => ({
    id: src.id,
    title: src.title,
    citation: `${src.publisher ?? src.kind} · ${src.why}`,
    url: src.url,
    retrievedAt: new Date().toISOString(),
    publicRecord: Boolean(src.publicRecord),
  }))
}
