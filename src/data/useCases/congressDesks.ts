/** Upgrade thin/boilerplate extraClaims into desk-specific verification claims */
function hardenExtraClaims(seed: DeskSeed): DeskSeed['extraClaims'] {
  const thin = seed.extraClaims.every(
    (c) =>
      /publishes primary materials used in compliance/i.test(c.statement) ||
      /single social post fully states legal duties/i.test(c.statement) ||
      /All firms face identical costs/i.test(c.statement) ||
      /Congress\.gov search is not enrolled text/i.test(c.statement) ||
      /Oversight can change private compliance cost in/i.test(c.statement),
  )
  if (!thin && seed.extraClaims.length >= 3) return seed.extraClaims
  return [
    {
      statement: `${seed.agency} (${seed.agencyUrl.replace(/^https?:\/\//, '').split('/')[0]}) is the public-record entry for operators working ${seed.title} — cite the specific instrument before asserting a duty on ${seed.industry}.`,
      score: 1 as EvidenceScore,
      material: 'secondary' as MaterialClass,
      notes: seed.agencyWhy,
    },
    {
      statement: `No social post or secondary commentary alone establishes enforceable legal duties for ${seed.industry} under ${seed.short}.`,
      score: -1 as EvidenceScore,
      material: 'assumption' as MaterialClass,
      notes: 'Disqualify social-only duty claims; attach enrolled text or agency instrument.',
    },
    {
      statement: `${seed.billHint} is a discovery aid; result pages are not enrolled bill text governing ${seed.industry}.`,
      score: 1 as EvidenceScore,
      material: 'secondary' as MaterialClass,
      notes: 'Open specific measures for operative language before +1 mandate claims.',
    },
    {
      statement: `Compliance cost and market-access effects on ${seed.industry} from ${seed.short} oversight are directionally plausible but unquantified without firm-level filings or GAO-class studies.`,
      score: 0 as EvidenceScore,
      material: 'derived' as MaterialClass,
      notes: 'Direction ≠ magnitude; hold 0 until primary cost evidence.',
    },
    {
      statement: `Impact of any ${seed.short} rule change is heterogeneous across ${seed.industry} by firm size, product line, and multi-jurisdiction load — identical-cost claims remain unproven.`,
      score: 0 as EvidenceScore,
      material: 'assumption' as MaterialClass,
      notes: 'Heterogeneous industry surface — do not generalize anecdotes.',
    },
    {
      statement: `Export / publish of ${seed.short} findings requires clearing open −1 rumor-as-law lines and binding +1 duty claims to ${seed.agency} or enrolled text.`,
      score: 1 as EvidenceScore,
      material: 'derived' as MaterialClass,
      notes: 'Layer-0 style gate for this desk family.',
    },
  ]
}

function buildReport(seed: DeskSeed): UseCaseReport {
  const hardened = { ...seed, extraClaims: hardenExtraClaims(seed) }
  const baseClaims = [
    claim(
      `${seed.id}-c1`,
      `Congressional and/or agency oversight activity touching ${seed.industry} is a live training topic as of ${AS_OF} (${seed.short}).`,
      1,
      'secondary',
      `Hearing calendars, ${seed.agency} pages, and congress.gov trails support an active desk — not a closed case file.`,
      seed.tags,
    ),
    claim(
      `${seed.id}-c2`,
      `Private-sector compliance cost and operational redesign are material risk channels for ${seed.industry} under ${seed.short}.`,
      1,
      'derived',
      seed.stakes,
      [...seed.tags, 'private-effects'],
    ),
    claim(
      `${seed.id}-c3`,
      `Viral posts asserting a final nationwide ban/mandate on ${seed.short} without citing enrolled text should default to 0 until primary law is attached.`,
      0,
      'assumption',
      'Desk hygiene rule for high-velocity policy claims.',
      ['hygiene', 'primary-text', seed.id],
    ),
  ]
  const extras = hardened.extraClaims.map((c, i) =>
    claim(`${seed.id}-x${i + 1}`, c.statement, c.score, c.material, c.notes, seed.tags),
  )
  return report({
    asOf: AS_OF,
    trendSignal: `Congressional oversight + industry compliance chatter · ${seed.short}`,
    headline: seed.title,
    executiveSummary: `${seed.lede} Industry surface: ${seed.industry}. Stakes: ${seed.stakes} This is a training desk — scores are operator judgments for evidence hygiene, not judicial findings.`,
    claims: [...baseClaims, ...extras],
    timeline: [
      { when: '2025–2026', what: 'Committee hearings and draft bills circulate in this issue family.' },
      { when: 'Ongoing', what: `${seed.agency} maintains public guidance/enforcement materials.` },
      { when: AS_OF, what: 'Desk assembled for NEXOSxLPIN training with stable official links.' },
      { when: 'Export gate', what: 'Resolve −1 rumor claims; attach enrolled text before asserting mandates.' },
    ],
    openQuestions: [
      'What is the latest enrolled public law text (not a fact sheet alone)?',
      'Which private entities are directly regulated vs indirectly affected?',
      'What are quantified compliance cost ranges from primary filings or GAO?',
      'Are there conflicting state regimes creating multi-jurisdiction load?',
      'What litigation could stay or vacate key provisions?',
    ],
    verificationPlaybook: [
      'Pull congress.gov bill status + enrolled text if claiming enactment.',
      'Attach agency primary page (rule, NOFO, or guidance) before +1 on duties.',
      'Map private effects: product, contracts, capital, insurance.',
      'Run SME lenses: Evidence Gate + relevant technical/sector lens.',
      'Hold export while −1 rumor claims remain open.',
    ],
    sourcesToSeek: [
      'Enrolled bill / public law PDF',
      'Committee report or hearing transcript',
      'GAO or CRS issue brief',
      `${seed.agency} primary page`,
      'Industry 10-K risk factor language (if public issuer)',
    ],
    noiseRisks: [
      'Campaign rhetoric treated as enacted law',
      'Out-of-date fact sheets after court stays',
      'Anecdotes generalized to entire industry',
      'Partisan framing that erases primary text',
    ],
    geographicNotes: seed.cityHint,
  })
}

