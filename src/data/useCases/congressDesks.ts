function claim(
  id: string,
  statement: string,
  score: EvidenceScore,
  material: MaterialClass,
  notes: string,
  tags: string[],
) {
  return {
    id,
    statement,
    score,
    material,
    confidence: (score === 1 ? 'high' : score === -1 ? 'medium' : 'low') as
      | 'high'
      | 'medium'
      | 'low',
    notes,
    tags,
  }
}

function md(report: Omit<UseCaseReport, 'fullBriefMarkdown'>): string {
  const lines = [
    `# ${report.headline}`,
    '',
    `**As of:** ${report.asOf} · **Signal:** ${report.trendSignal}`,
    '',
    '## Executive summary',
    '',
    report.executiveSummary,
    '',
    '## Scored claims',
    '',
    ...report.claims.map(
      (c) =>
        `- **[${c.score === 1 ? '+1' : c.score === -1 ? '−1' : '0'}]** ${c.statement}\n  - _${c.material} · ${c.confidence}_ — ${c.notes}`,
    ),
    '',
    '## Timeline',
    '',
    ...report.timeline.map((t) => `- **${t.when}** — ${t.what}`),
    '',
    '## Open questions',
    '',
    ...report.openQuestions.map((q) => `- ${q}`),
    '',
    '## Verification playbook',
    '',
    ...report.verificationPlaybook.map((s, i) => `${i + 1}. ${s}`),
    '',
    '## Sources to seek',
    '',
    ...report.sourcesToSeek.map((s) => `- ${s}`),
    '',
    '## Noise risks',
    '',
    ...report.noiseRisks.map((n) => `- ${n}`),
    '',
    '_NEXOSxLPIN congressional training desk · Layer-0 export · not legal advice._',
    '',
  ]
  return lines.join('\n')
}

function report(r: Omit<UseCaseReport, 'fullBriefMarkdown'>): UseCaseReport {
  return { ...r, fullBriefMarkdown: md(r) }
}

